#!/usr/bin/env bash
#
# build_wsb.sh
#
# Regenerate windows_sandbox.wsb with sandbox_setup.ps1 embedded in its
# LogonCommand, so the .wsb is a single self-contained file that runs from any
# folder. Windows Sandbox doesn't support relative <HostFolder> paths, so
# mapping the script in would tie the .wsb to one absolute location.
#
# The script is gzipped and base64-encoded; the LogonCommand decodes it to
# %TEMP%\sandbox_setup.ps1 inside the sandbox and runs it. Run this after every
# change to sandbox_setup.ps1 and commit both files.
#
# Usage:
#   build_wsb.sh            Rewrite windows_sandbox.wsb.
#   build_wsb.sh --check    Exit 1 if windows_sandbox.wsb is out of date.
#
# Requirements: bash, coreutils (base64), gzip.
#
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
SETUP_PS1="$SCRIPT_DIR/sandbox_setup.ps1"
WSB="$SCRIPT_DIR/windows_sandbox.wsb"

CHECK=false
case "${1:-}" in
  "") ;;
  --check) CHECK=true ;;
  -h | --help)
    sed -n '3,18p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  *)
    echo "Error: unknown argument: $1" >&2
    exit 1
    ;;
esac

for cmd in base64 gzip; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: '$cmd' not found." >&2
    exit 1
  fi
done

if [[ ! -f "$SETUP_PS1" ]]; then
  echo "Error: not found: $SETUP_PS1" >&2
  exit 1
fi

# -n leaves the file name and timestamp out of the gzip header, so the output
# only changes when the script does.
payload="$(gzip -9 -n <"$SETUP_PS1" | base64 -w0)"

# Single quotes only inside the command (it is wrapped in double quotes), and
# & is written as &amp; because this is XML.
logon_command="powershell.exe -NoProfile -ExecutionPolicy Bypass -Command \"\$p = Join-Path \$env:TEMP 'sandbox_setup.ps1'; \$b = [Convert]::FromBase64String('$payload'); \$g = New-Object IO.Compression.GZipStream((New-Object IO.MemoryStream(,\$b)), [IO.Compression.CompressionMode]::Decompress); \$f = [IO.File]::Create(\$p); \$g.CopyTo(\$f); \$f.Close(); &amp; \$p\""

render() {
  cat <<EOF
<Configuration>
  <!--
    windows_sandbox.wsb

    GENERATED by build_wsb.sh - do not edit by hand. Edit sandbox_setup.ps1,
    then run ./configs/windows_sandbox/build_wsb.sh and commit both files.

    Windows Sandbox with dark mode, winget and the Microsoft Store set up at logon
    by sandbox_setup.ps1 (see that script for details), which is embedded below
    gzipped and base64-encoded. Setup takes a few minutes after the desktop
    appears, and its log is written to the sandbox desktop.

    Self-contained: copy just this file anywhere on the Windows host and
    double-click it.

    Requirements: Windows 11 with the Windows Sandbox feature enabled.
  -->
  <LogonCommand>
    <Command>$logon_command</Command>
  </LogonCommand>
</Configuration>
EOF
}

if [[ "$CHECK" == true ]]; then
  if ! diff -q <(render) "$WSB" >/dev/null 2>&1; then
    echo "Error: $WSB is out of date; run $0 and commit the result." >&2
    exit 1
  fi
  echo "windows_sandbox.wsb is up to date."
  exit 0
fi

render >"$WSB"
echo "Wrote $WSB (${#logon_command} character LogonCommand)."
